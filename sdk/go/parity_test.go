// TestDescriptorTableIsComplete guards allHookDescriptors() against a
// descriptor declared in hook_descriptors.go but left out of the table. Such a
// descriptor would be usable but invisible to every parity check above, which
// is worse than not having it.
func TestDescriptorTableIsComplete(t *testing.T) {
	src, err := os.ReadFile("hook_descriptors.go")
	if err != nil {
		t.Fatalf("read hook_descriptors.go: %v", err)
	}
	body := string(src)

	listed := map[string]bool{}
	for _, d := range allHookDescriptors() {
		listed[d.Name] = true
	}

	// Each descriptor is declared as `var HookX = Hook[...]{Name: HookNameX}`.
	// Count the declarations and compare with the table's length: a name-level
	// comparison is not possible without evaluating the constants, but a count
	// mismatch catches the omission this test exists for.
	declared := strings.Count(body, "= Hook[")
	if declared != len(listed) {
		t.Errorf("hook_descriptors.go declares %d descriptors but allHookDescriptors() lists %d.\n"+
			"Every `var HookX = Hook[...]` must appear in allHookDescriptors(), or the parity "+
			"tests cannot see it.", declared, len(listed))
	}
}

// --- helpers ---

func isRawMessageType(rt reflect.Type) bool {
	if rt == nil {
		return false
	}
	if rt == reflect.TypeOf(json.RawMessage{}) {
		return true
	}
	// ToolInput and ToolResultInfo are named json.RawMessage types.
	return rt.Kind() == reflect.Slice && rt.Elem().Kind() == reflect.Uint8
}

// jsonFieldNamesOf returns a struct's sorted JSON field names, matching the
// engine generator's extraction so the two lists are comparable.
func jsonFieldNamesOf(rt reflect.Type) []string {
	for rt != nil && rt.Kind() == reflect.Ptr {
		rt = rt.Elem()
	}
	if rt == nil || rt.Kind() != reflect.Struct {
		return nil
	}
	var names []string
	for i := range rt.NumField() {
		f := rt.Field(i)
		tag := f.Tag.Get("json")
		if tag == "" || tag == "-" {
			continue
		}
		name := strings.Split(tag, ",")[0]
		if name == "" {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func containsString(haystack []string, needle string) bool {
	for _, s := range haystack {
		if s == needle {
			return true
		}
	}
	return false
}
